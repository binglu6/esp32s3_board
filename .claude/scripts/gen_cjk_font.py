#!/usr/bin/env python
"""Generate a 16 px GB2312 CJK bitmap font for LVGL v9.

The bundled LVGL CJK fonts only cover ~1300 glyphs and are missing very common
characters such as 音/乐/播/卡, so this script rasterises the 6763 GB2312
level-1 + level-2 hanzi with SimHei into a sparse `lv_font_fmt_txt` font (1 bpp).

Output:
  components/bsp/bsp_ai_code/bsp_ai_font_cjk_16.c
  components/bsp/bsp_ai_code/bsp_ai_font_cjk_16.h

ASCII is not included: the font's fallback is lv_font_montserrat_16.
"""
import os

from PIL import Image, ImageDraw, ImageFont

CELL = 16
SCALE = 4
THRESHOLD = 96
FONT_PATH = r"C:\Windows\Fonts\simhei.ttf"

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, "components", "bsp", "bsp_ai_code")
C_PATH = os.path.join(OUT_DIR, "bsp_ai_font_cjk_16.c")
H_PATH = os.path.join(OUT_DIR, "bsp_ai_font_cjk_16.h")
PREVIEW = os.path.join(ROOT, "build", "cjk_font_preview.png")


def gb2312_chars():
    chars = []
    # 0xA1A1-0xA9FE: symbols; 0xB0A1-0xD7F9: level 1; 0xD8A1-0xF7FE: level 2
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            chars.append(ch)
    # keep codepoint order so the sparse unicode_list is sorted
    return sorted(set(chars), key=ord)


def rasterise(chars, font):
    """Return {codepoint: 32-byte packed bitmap}."""
    glyphs = {}
    for ch in chars:
        big = Image.new("L", (CELL * SCALE, CELL * SCALE), 0)
        ImageDraw.Draw(big).text((CELL * SCALE // 2, CELL * SCALE // 2), ch,
                                 font=font, fill=255, anchor="mm")
        small = big.resize((CELL, CELL), Image.LANCZOS)
        small = small.point(lambda p: 255 if p >= THRESHOLD else 0)
        px = small.load()
        data = bytearray()
        for y in range(CELL):
            row = 0
            for x in range(CELL):
                row = (row << 1) | (1 if px[x, y] else 0)
            data += row.to_bytes(2, "big")
        glyphs[ord(ch)] = bytes(data)
    return glyphs


def preview(chars, glyphs):
    text = "音乐播放 SD卡 正在播放 已暂停 上一首 下一首 音量 返回 未找到音乐文件 刷新 谪仙 黄昏 甲乙丙丁 一路生花 雨爱 ，：（）！？、。；"
    width, height = 16 * len(text) + 8, 40
    img = Image.new("L", (width, height), 0)
    x = 4
    for ch in text:
        if ch == " ":
            x += 8
            continue
        cp = ord(ch)
        if cp < 0x80:
            # ASCII is handled by Montserrat at runtime; skip in preview
            x += 8
            continue
        bits = glyphs.get(cp)
        if bits is None:
            x += CELL
            continue
        for yy in range(CELL):
            row = int.from_bytes(bits[yy * 2:yy * 2 + 2], "big")
            for xx in range(CELL):
                if row & (0x8000 >> xx):
                    img.putpixel((x + xx, 12 + yy), 255)
        x += CELL
    img = img.resize((width * 4, height * 4), Image.NEAREST)
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    img.save(PREVIEW)
    print("preview:", PREVIEW)


def write_font(chars, glyphs):
    # glyph 0 is the reserved "missing" glyph
    codepoints = [ord(ch) for ch in chars]
    range_start = codepoints[0]
    range_end = codepoints[-1]
    range_length = range_end - range_start + 1

    bitmap = bytearray()
    for cp in codepoints:
        bitmap += glyphs[cp]

    lines = []
    lines.append("// bsp_ai_font_cjk_16.c — auto-generated 16 px GB2312 (L1+L2) font")
    lines.append("// Generated by .claude/scripts/gen_cjk_font.py, do not edit by hand.")
    lines.append('#include "bsp_ai_font_cjk_16.h"')
    lines.append("")
    lines.append('LV_FONT_DECLARE(lv_font_montserrat_16);')
    lines.append("")
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 24]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    lines.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for i in range(len(codepoints)):
        lines.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = 0, .ofs_y = -2},"
                     % (i * CELL * 2, CELL * 16, CELL, CELL))
    lines.append("};")
    lines.append("")
    lines.append("static const uint16_t unicode_list_1[] = {")
    offsets = [cp - range_start for cp in codepoints]
    for i in range(0, len(offsets), 12):
        lines.append("    " + ", ".join("0x%04x" % o for o in offsets[i:i + 12]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    lines.append("    {")
    lines.append("        .range_start = %d, /* U+%04X */" % (range_start, range_start))
    lines.append("        .range_length = %d," % range_length)
    lines.append("        .glyph_id_start = 1,")
    lines.append("        .unicode_list = unicode_list_1,")
    lines.append("        .glyph_id_ofs_list = NULL,")
    lines.append("        .list_length = %d," % len(offsets))
    lines.append("        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,")
    lines.append("    },")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    lines.append("    .glyph_bitmap = glyph_bitmap,")
    lines.append("    .glyph_dsc = glyph_dsc,")
    lines.append("    .cmaps = cmaps,")
    lines.append("    .kern_dsc = NULL,")
    lines.append("    .kern_scale = 0,")
    lines.append("    .cmap_num = 1,")
    lines.append("    .bpp = 1,")
    lines.append("    .kern_classes = 0,")
    lines.append("    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,")
    lines.append("    .stride = 0,")
    lines.append("};")
    lines.append("")
    lines.append("const lv_font_t bsp_ai_font_cjk_16 = {")
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    lines.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append("    .line_height = 18,")
    lines.append("    .base_line = 3,")
    lines.append("    .subpx = LV_FONT_SUBPX_NONE,")
    lines.append("    .underline_position = -2,")
    lines.append("    .underline_thickness = 1,")
    lines.append("    .dsc = &font_dsc,")
    lines.append("    .fallback = &lv_font_montserrat_16,")
    lines.append("};")
    lines.append("")

    with open(C_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    header = """// bsp_ai_font_cjk_16.h
#ifndef BSP_AI_FONT_CJK_16_H
#define BSP_AI_FONT_CJK_16_H

#pragma once

#include "lvgl.h"

/** 16 px GB2312 (level 1 + level 2) CJK font; ASCII falls back to Montserrat 16. */
LV_FONT_DECLARE(bsp_ai_font_cjk_16);

#endif // BSP_AI_FONT_CJK_16_H
"""
    with open(H_PATH, "w", encoding="utf-8") as f:
        f.write(header)

    print("glyphs: %d, bitmap: %d bytes" % (len(codepoints), len(bitmap)))
    print("wrote %s" % C_PATH)
    print("wrote %s" % H_PATH)


def main():
    chars = gb2312_chars()
    font = ImageFont.truetype(FONT_PATH, CELL * SCALE)
    glyphs = rasterise(chars, font)
    preview(chars, glyphs)
    write_font(chars, glyphs)


if __name__ == "__main__":
    main()
